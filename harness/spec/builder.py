"""Turn alignment findings into actionable, traceable change specs."""
from __future__ import annotations

from ..models import (
    APICall,
    BusinessRule,
    ChangeSpec,
    ComponentInfo,
    EntityAlignment,
    MockDataset,
    Requirement,
    TargetEndpoint,
    TargetEntity,
    UIContract,
)
from ..utils import name_similarity

_CHANGE_STATUSES = {
    "FIELD_RENAME", "TYPE_MISMATCH", "ENUM_MISMATCH", "ENUM_NOT_ENFORCED",
    "REQUIRED_MISSING", "OPTIONAL_MISSING", "UI_ONLY_FIELD",
}


def _requirements_for_entity(entity: str, requirements: list[Requirement]) -> list[str]:
    needle = entity.lower()
    return [
        r.id for r in requirements
        if needle in (r.title + " " + r.body).lower()
    ]


def _mock_files(entity: str, datasets: list[MockDataset]) -> list[str]:
    return sorted({
        ds.file for ds in datasets
        if name_similarity(ds.entity, entity) >= 0.72
    })


def _components_for_entity(
    entity: str, ui_contract: str, components: list[ComponentInfo], field_names: set[str]
) -> list[ComponentInfo]:
    touched: list[ComponentInfo] = []
    for comp in components:
        if ui_contract in comp.contracts_used:
            touched.append(comp)
        elif field_names & set(comp.field_accesses):
            touched.append(comp)
    return touched


def _llm_migration_note(provider, spec_ctx: dict) -> str:
    if not getattr(provider, "enabled", False):
        return ""
    system = (
        "You are a senior frontend architect. Given a contract alignment for a "
        "React/TypeScript app generated by Lovable, return 3-5 concise, concrete "
        "implementation bullets for migrating the UI to the target contract. "
        "No preamble, no headings, one bullet per line."
    )
    import json
    user = json.dumps(spec_ctx, indent=2)[:6000]
    return provider.complete(system, user)


def build_entity_specs(
    alignments: list[EntityAlignment],
    contracts: list[UIContract],
    datasets: list[MockDataset],
    components: list[ComponentInfo],
    targets: list[TargetEntity],
    rules: list[BusinessRule],
    requirements: list[Requirement],
    provider,
) -> list[ChangeSpec]:
    specs: list[ChangeSpec] = []
    target_by_name = {t.name: t for t in targets}
    contract_by_name = {c.name: c for c in contracts}

    for idx, alignment in enumerate(alignments, start=1):
        target = target_by_name[alignment.target_entity]
        ui_contract = contract_by_name.get(alignment.ui_contract)
        field_names = {m.ui_field for m in alignment.field_mappings if m.ui_field != "—"}
        touched_components = _components_for_entity(
            target.name, alignment.ui_contract, components, field_names
        )

        files: list[str] = []
        if ui_contract:
            files.append(ui_contract.source_file)
        files.extend(_mock_files(target.name, datasets))
        files.extend(c.file for c in touched_components)
        files = sorted(set(files))

        changes: list[str] = []
        acceptance: list[str] = []
        rule_ids: set[str] = set()
        for m in alignment.field_mappings:
            if m.status not in _CHANGE_STATUSES:
                continue
            if m.status == "UI_ONLY_FIELD":
                changes.append(f"Remove or explicitly remap dummy-only field `{m.ui_field}`.")
            elif m.status in ("REQUIRED_MISSING", "OPTIONAL_MISSING"):
                changes.append(
                    f"Add `{m.target_field}: {m.target_type}` "
                    f"({'required' if m.required_in_target else 'optional'}) and surface it in the UI."
                )
                acceptance.append(
                    f"Component renders a non-crashing value for `{m.target_field}` "
                    "for empty, loading and populated states."
                )
            elif m.status == "FIELD_RENAME":
                changes.append(f"Rename `{m.ui_field}` to `{m.target_field}` (type stays compatible).")
                acceptance.append(f"No remaining reference to legacy field `{m.ui_field}`.")
            elif m.status == "TYPE_MISMATCH":
                changes.append(
                    f"Introduce an adapter for `{m.ui_field}` -> `{m.target_field}`: {m.note}"
                )
                acceptance.append(f"Unit test covers conversion `{m.ui_field}` -> `{m.target_field}`.")
            elif m.status in ("ENUM_MISMATCH", "ENUM_NOT_ENFORCED"):
                changes.append(f"Constrain `{m.target_field}` to the target enum and update badge/select logic: {m.note}")
                acceptance.append("All target enum values are rendered; unknown values fall back safely.")

        for finding in alignment.findings:
            rule_ids.update(finding.rule_ids)
        for fld in target.fields:
            rule_ids.update(fld.rule_ids)

        # Rule acceptance criteria ride along on the entity spec.
        for rule in rules:
            if rule.id in rule_ids:
                acceptance.extend(f"{rule.id}: {a}" for a in rule.acceptance)

        current = (
            f"UI contract `{alignment.ui_contract}` "
            f"({'declared' if ui_contract and not ui_contract.inferred else 'inferred from mock data'}) "
            f"matched target `{target.name}` with confidence {alignment.match_confidence}. "
            f"{len(alignment.findings)} finding(s)."
        )
        target_state = (
            f"Implement `{target.name}` exactly as defined in {target.source} "
            f"({len(target.fields)} fields)."
        )

        spec = ChangeSpec(
            spec_id=f"SPEC-E{idx:02d}",
            title=f"Align {alignment.ui_contract} with target contract {target.name}",
            scope="entity",
            target_entity=target.name,
            current_state=current,
            target_state=target_state,
            changes=changes or ["No structural changes detected; verify formatting and null handling."],
            files=files,
            acceptance_criteria=sorted(set(acceptance)) or [
                "Existing behavior preserved under real-contract fixtures."
            ],
            rule_ids=sorted(rule_ids),
            requirement_ids=_requirements_for_entity(target.name, requirements),
            evidence=[f"{f.code}: {f.message}" for f in alignment.findings],
        )

        note = _llm_migration_note(provider, {
            "spec": spec.spec_id,
            "entity": target.name,
            "mappings": [m.__dict__ for m in alignment.field_mappings],
            "components": [c.name for c in touched_components],
        })
        if note:
            spec.changes.extend(f"(LLM suggestion) {line}" for line in note.splitlines() if line.strip())
        specs.append(spec)
    return specs


def build_component_specs(
    alignments: list[EntityAlignment],
    components: list[ComponentInfo],
) -> list[ChangeSpec]:
    specs: list[ChangeSpec] = []
    idx = 1
    # One legacy field can map differently per entity (e.g. id -> orderId / lineId).
    field_renames: dict[str, list[tuple[str, str, str]]] = {}
    for alignment in alignments:
        for m in alignment.field_mappings:
            if m.ui_field != "—" and m.target_field != "—" and m.ui_field != m.target_field:
                field_renames.setdefault(m.ui_field, []).append(
                    (m.target_field, alignment.target_entity, m.status)
                )

    for comp in components:
        if not comp.mock_used and not comp.api_used:
            continue
        changes: list[str] = []
        if comp.mock_used:
            changes.append(
                f"Remove mock import(s) {', '.join(comp.mock_used)} and source data from the "
                "real API client / query hook instead."
            )
        for legacy, mappings in field_renames.items():
            if legacy not in comp.field_accesses:
                continue
            for new, entity, status in mappings:
                changes.append(
                    f"Update field access `{legacy}` -> `{new}` on {entity} ({status})."
                )
        if not comp.api_used and comp.mock_used:
            changes.append("Add loading, error and empty states (mock data never exercises them).")
        if not changes:
            continue
        specs.append(
            ChangeSpec(
                spec_id=f"SPEC-C{idx:02d}",
                title=f"Migrate component {comp.name} to live contracts",
                scope="component",
                target_entity="",
                current_state=(
                    f"{comp.name} uses mock data={comp.mock_used or 'none'}, "
                    f"api={comp.api_used or 'none'}, contracts={comp.contracts_used}."
                ),
                target_state="Component is presentational; data arrives via typed query hooks.",
                changes=changes,
                files=[comp.file],
                acceptance_criteria=[
                    "Renders against a real-contract fixture without dummy imports.",
                    "Loading, error and empty states verified.",
                ],
                evidence=[f"props: {', '.join(comp.props) or 'none'}"],
            )
        )
        idx += 1
    return specs


def build_api_spec(
    endpoints: list[TargetEndpoint], api_calls: list[APICall]
) -> ChangeSpec:
    call_targets = {c.target for c in api_calls}
    changes: list[str] = []
    for ep in endpoints:
        covered = any(ep.path in t or t.endswith(ep.path) for t in call_targets)
        if not covered:
            changes.append(
                f"Add typed client call for {ep.method} {ep.path} "
                f"(entity: {ep.response_entity or ep.request_entity or 'n/a'})."
            )
    if not api_calls:
        changes.append("No data-access calls detected — the UI appears fully mock-driven; create the API layer.")
    elif not changes:
        changes.append("All target endpoints have a detected call site; verify request/response typing.")
    return ChangeSpec(
        spec_id="SPEC-X01",
        title="Align API client layer with target endpoints",
        scope="cross_cutting",
        target_entity="",
        current_state=f"Detected {len(api_calls)} call site(s); {len(endpoints)} target endpoint(s).",
        target_state="Typed client functions covering every target endpoint with contract-validated IO.",
        changes=changes,
        files=sorted({c.file for c in api_calls}),
        acceptance_criteria=[
            "Each target endpoint has exactly one typed client function.",
            "Runtime schema validation (zod/valibot or equivalent) on every response.",
        ],
        rule_ids=sorted({r for ep in endpoints for r in ep.rule_ids}),
    )


_STOPWORDS = {
    "the", "and", "for", "with", "that", "this", "from", "when", "then",
    "given", "must", "will", "are", "was", "were", "been", "being", "into",
    "per", "can", "may", "only", "any", "all", "not", "but", "out", "off",
}


def _significant_tokens(text: str) -> set[str]:
    import re
    return {
        tok for tok in re.findall(r"[a-z]{4,}", text.lower())
        if tok not in _STOPWORDS
    }


def link_requirements_to_rule(rule: BusinessRule, requirements: list[Requirement]) -> list[str]:
    rule_tokens = _significant_tokens(rule.title + " " + rule.description)
    linked: list[str] = []
    for req in requirements:
        req_tokens = _significant_tokens(req.title + " " + req.body)
        if rule_tokens & req_tokens:
            linked.append(req.id)
    return linked


def build_rule_specs(
    rules: list[BusinessRule], global_findings, requirements: list[Requirement]
) -> list[ChangeSpec]:
    gap_rule_ids = {f.rule_ids[0] for f in global_findings if f.code == "RULE_FIELD_GAP" and f.rule_ids}
    specs: list[ChangeSpec] = []
    for idx, rule in enumerate(rules, start=1):
        if rule.id not in gap_rule_ids:
            continue
        specs.append(
            ChangeSpec(
                spec_id=f"SPEC-R{idx:02d}",
                title=f"Implement business rule {rule.id} — {rule.title}",
                scope="cross_cutting",
                target_entity=", ".join(rule.applies_to),
                current_state=rule.description,
                target_state=f"Rule {rule.id} enforced and covered by automated tests.",
                changes=[
                    f"Encode {rule.id} in the domain/adapter layer (keep it out of presentational components).",
                    f"Required fields: {', '.join(rule.requires_fields) or 'see rule body'}.",
                ],
                acceptance_criteria=rule.acceptance or [
                    f"Automated test demonstrates {rule.id} for happy path and at least one violation case."
                ],
                rule_ids=[rule.id],
                requirement_ids=link_requirements_to_rule(rule, requirements),
                evidence=[
                    f.message for f in global_findings
                    if f.rule_ids and f.rule_ids[0] == rule.id
                ],
            )
        )
    return specs


def build_all_specs(
    alignments, contracts, datasets, components, targets, endpoints,
    api_calls, rules, requirements, global_findings, provider,
) -> list[ChangeSpec]:
    return (
        build_entity_specs(alignments, contracts, datasets, components, targets, rules, requirements, provider)
        + build_component_specs(alignments, components)
        + [build_api_spec(endpoints, api_calls)]
        + build_rule_specs(rules, global_findings, requirements)
    )
